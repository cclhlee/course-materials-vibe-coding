-- ★ 起始版本（請找出待修正之處，共 3 個錯誤）--------------------

-- 錯誤1：忘記WHERE子句，會把所有掛號記錄的科別都改成「家醫科」
UPDATE 掛號記錄 SET 科別 = '家醫科';

-- 錯誤2：JOIN條件寫錯，用病患ID去對應用藥紀錄的用藥ID（邏輯不通）
SELECT * FROM 掛號記錄
JOIN 用藥紀錄 ON 掛號記錄.病患ID = 用藥紀錄.用藥ID;

-- 錯誤3：字串拼接使用者輸入，存在SQL injection風險（僅示意，非可直接執行的合法SQL）
-- SELECT * FROM 病患 WHERE 姓名 = '" + 使用者輸入姓名 + "';


-- ✓ 修正版本（解答）--------------------------------------------

-- 修正1：加上WHERE子句，只更新指定掛號ID的記錄
UPDATE 掛號記錄 SET 科別 = '家醫科' WHERE 掛號ID = 101;

-- 修正2：JOIN條件改為正確的外鍵關聯（掛號記錄.掛號ID = 用藥紀錄.掛號ID）
SELECT * FROM 掛號記錄
JOIN 用藥紀錄 ON 掛號記錄.掛號ID = 用藥紀錄.掛號ID;

-- 修正3：改用參數化查詢，使用者輸入永遠被當作資料值而非SQL語法的一部分
-- （實際應用中由應用程式端的資料庫函式庫代入參數，例如 node-postgres 的寫法）
