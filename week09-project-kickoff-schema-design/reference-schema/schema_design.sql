DROP TABLE IF EXISTS 服藥紀錄;
DROP TABLE IF EXISTS 用藥時程;
DROP TABLE IF EXISTS 使用者;

-- 1. 使用者：系統的主要使用者（獨居長者，或協助管理的家屬）
--    對應使用者故事：「身為獨居長者的家屬，我想要在長輩沒有按時服藥時收到通知，
--    以便我能及時關心並提醒他們服藥。」
CREATE TABLE 使用者 (
  使用者ID SERIAL PRIMARY KEY,
  姓名 VARCHAR(50) NOT NULL,
  聯絡電話 VARCHAR(20)
);

-- 2. 用藥時程：每位使用者設定的用藥排程
--    對應使用者故事：「身為獨居長者，我想要在正確的時間收到服藥提醒，
--    以便我不會忘記或重複服藥。」
--    修正重點（練習2 codeGood）：使用者ID改用外鍵關聯（而非重複儲存姓名），
--    藥名/劑量加上NOT NULL，避免不完整資料寫入。
CREATE TABLE 用藥時程 (
  時程ID SERIAL PRIMARY KEY,
  使用者ID INTEGER NOT NULL REFERENCES 使用者(使用者ID),
  藥名 VARCHAR(50) NOT NULL,
  劑量 VARCHAR(20) NOT NULL,
  服用時間 TIME NOT NULL,
  頻率 VARCHAR(20)
);

-- 3. 服藥紀錄：每次應服藥時間點的實際服用狀態
--    對應使用者故事：「身為家屬，我想要查看長輩過去一週的服藥紀錄，
--    以便我了解他們的服藥狀況是否穩定。」
--    修正重點（練習2 codeGood）：時程ID改用外鍵關聯，
--    服用日期改用TIMESTAMP型態（而非VARCHAR字串），避免日期排序/比較錯誤，
--    狀態欄位加上NOT NULL與預設值。
CREATE TABLE 服藥紀錄 (
  紀錄ID SERIAL PRIMARY KEY,
  時程ID INTEGER NOT NULL REFERENCES 用藥時程(時程ID),
  服用日期時間 TIMESTAMP NOT NULL,
  狀態 VARCHAR(10) NOT NULL DEFAULT '未服用'
);

