-- 驗證1：查詢王奶奶的所有用藥時程（透過使用者ID外鍵關聯，而非重複比對姓名字串）
SELECT 使用者.姓名, 用藥時程.藥名, 用藥時程.劑量, 用藥時程.服用時間
FROM 用藥時程
JOIN 使用者 ON 用藥時程.使用者ID = 使用者.使用者ID
WHERE 使用者.姓名 = '王奶奶';

-- 驗證2：查詢過去一週服藥紀錄，並可正確依日期時間排序（因型態為TIMESTAMP而非VARCHAR）
SELECT 用藥時程.藥名, 服藥紀錄.服用日期時間, 服藥紀錄.狀態
FROM 服藥紀錄
JOIN 用藥時程 ON 服藥紀錄.時程ID = 用藥時程.時程ID
ORDER BY 服藥紀錄.服用日期時間 DESC;

