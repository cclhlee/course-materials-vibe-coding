-- ------------------------------------------------------------
-- 核心功能查詢範例
-- ------------------------------------------------------------

-- 核心功能二：依當前時間自動顯示「今日待服用清單」（以 2026-08-22 為例）
SELECT 用藥時程.藥名, 用藥時程.劑量, 用藥時程.服用時間
FROM 用藥時程
LEFT JOIN 服藥紀錄
  ON 用藥時程.時程ID = 服藥紀錄.時程ID
  AND 服藥紀錄.服用日期時間::date = '2026-08-22'
WHERE 用藥時程.使用者ID = 1
  AND (服藥紀錄.狀態 IS NULL OR 服藥紀錄.狀態 = '未服用');

-- 核心功能三：查詢某位使用者的歷史服藥紀錄（供家屬查看）
SELECT 用藥時程.藥名, 服藥紀錄.服用日期時間, 服藥紀錄.狀態
FROM 服藥紀錄
JOIN 用藥時程 ON 服藥紀錄.時程ID = 用藥時程.時程ID
WHERE 用藥時程.使用者ID = 1
ORDER BY 服藥紀錄.服用日期時間 DESC;
