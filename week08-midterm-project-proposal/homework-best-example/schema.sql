DROP TABLE IF EXISTS 服藥紀錄;
DROP TABLE IF EXISTS 用藥時程;
DROP TABLE IF EXISTS 使用者;

-- 1. 使用者：系統的主要使用者（獨居長者或協助管理的家屬）
CREATE TABLE 使用者 (
  使用者ID SERIAL PRIMARY KEY,
  姓名 VARCHAR(50) NOT NULL,
  聯絡電話 VARCHAR(20)
);

-- 2. 用藥時程：每位使用者設定的用藥排程
CREATE TABLE 用藥時程 (
  時程ID SERIAL PRIMARY KEY,
  使用者ID INTEGER REFERENCES 使用者(使用者ID),
  藥名 VARCHAR(50) NOT NULL,
  劑量 VARCHAR(20),
  服用時間 TIME NOT NULL,
  頻率 VARCHAR(20)
);

-- 3. 服藥紀錄：每次應服藥時間點的實際服用狀態（與教材codeGood區塊一致）
CREATE TABLE 服藥紀錄 (
  紀錄ID SERIAL PRIMARY KEY,
  時程ID INTEGER REFERENCES 用藥時程(時程ID),
  服用日期時間 TIMESTAMP NOT NULL,
  狀態 VARCHAR(10) DEFAULT '未服用'
);

